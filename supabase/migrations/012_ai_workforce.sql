-- Server-only durable Workforce storage; never exposed through the browser API.
CREATE SCHEMA archet_workforce;
REVOKE ALL ON SCHEMA archet_workforce FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE archet_workforce.conversations (
 id TEXT PRIMARY KEY, title TEXT NOT NULL, creator_id TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE archet_workforce.members (
 conversation_id TEXT NOT NULL REFERENCES archet_workforce.conversations(id), user_id TEXT NOT NULL,
 PRIMARY KEY(conversation_id,user_id));
CREATE TABLE archet_workforce.messages (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id TEXT NOT NULL REFERENCES archet_workforce.conversations(id),
 sender_id TEXT NOT NULL, sender_name TEXT NOT NULL, kind TEXT NOT NULL,
 content TEXT NOT NULL, created_at TEXT NOT NULL, task_id TEXT, request_id TEXT,
 UNIQUE(conversation_id,sender_id,request_id));
CREATE INDEX messages_chat ON archet_workforce.messages(conversation_id,seq);
CREATE INDEX messages_task ON archet_workforce.messages(task_id,seq);
CREATE TABLE archet_workforce.tasks (
 id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES archet_workforce.conversations(id),
 message_seq BIGINT NOT NULL REFERENCES archet_workforce.messages(seq), creator_id TEXT NOT NULL,
 session_version TEXT NOT NULL, model TEXT NOT NULL, status TEXT NOT NULL,
 step TEXT NOT NULL, created_at TEXT NOT NULL, started_at TEXT, completed_at TEXT,
 error TEXT, result TEXT, attempts INTEGER NOT NULL DEFAULT 0,
 lease_owner TEXT, lease_until DOUBLE PRECISION, cancel_requested INTEGER NOT NULL DEFAULT 0);
CREATE INDEX tasks_queue ON archet_workforce.tasks(status,created_at);
CREATE TABLE archet_workforce.audit (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id TEXT, actor_id TEXT NOT NULL,
 event TEXT NOT NULL, details TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE archet_workforce.settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE archet_workforce.workers (id TEXT PRIMARY KEY, heartbeat DOUBLE PRECISION NOT NULL);

REVOKE ALL ON ALL TABLES IN SCHEMA archet_workforce FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA archet_workforce FROM PUBLIC, anon, authenticated, service_role;

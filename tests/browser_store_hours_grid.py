"""Exercise real browser spreadsheet interactions against isolated review fixtures."""
from pathlib import Path
from playwright.sync_api import expect
from browser_store_hours import main

ROOT = Path(__file__).resolve().parents[1]


def check(page):
    def cell(address):
        return page.locator(f'#sh-table [data-address="{address}"]')

    def go(address):
        page.locator('#sh-grid-address').fill(address)
        page.locator('#sh-grid-address').press('Enter')

    def paste(text):
        page.evaluate('(text)=>navigator.clipboard.writeText(text)', text)
        page.keyboard.press('Control+v')

    def time(address, expected):
        expect(cell(address).locator('input[type=time]')).to_have_value(expected)

    expect(page.locator('.sh-sheet-welcome')).to_be_visible()
    page.locator('.sh-sheet-welcome [data-grid=tutorial]').click()
    for n in range(1, 6):
        expect(page.locator('#sh-grid-dialog-title')).to_contain_text(f'{n} of 5')
        page.locator('#sh-tutorial-next').click()
    expect(page.locator('#sh-grid-dialog')).not_to_be_visible()
    expect(page.locator('.sh-sheet-welcome')).to_be_hidden()

    # Navigation and range selection retain a single keyboard focus target.
    cell('F1').click()
    page.keyboard.press('ArrowRight')
    expect(cell('G1')).to_be_focused()
    page.keyboard.press('Shift+ArrowDown')
    expect(page.locator('#sh-grid-address')).to_have_value('G1:G2')
    page.keyboard.press('Shift+ArrowDown')
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(3)
    page.keyboard.press('Control+d')
    time('G2', '10:05:00')
    time('G3', '10:05:00')
    page.keyboard.press('Control+z')
    time('G2', '')
    time('G3', '')
    page.keyboard.press('Control+Shift+z')
    time('G3', '10:05:00')
    page.keyboard.press('Control+z')

    # A scalar paste fills a selected rectangle as one undo operation.
    go('F2:G3')
    paste('9:02 AM')
    for address in ['F2', 'G2', 'F3', 'G3']:
        time(address, '09:02:00')
    page.keyboard.press('Control+z')
    time('F2', '')
    time('G2', '')

    go('F2')
    paste('10:00 AM\t10:07 AM\r\n10:00:00\t10:09:00\r\n')
    time('G2', '10:07:00')
    time('G3', '10:09:00')
    expect(cell('N2')).to_have_text('-$10')
    expect(cell('N3')).to_have_text('-$10')
    page.keyboard.press('Control+c')
    assert page.evaluate('navigator.clipboard.readText()') == '10:00:00\t10:07:00\r\n10:00:00\t10:09:00'

    # Invalid or protected cells reject the whole paste, with no partial edits.
    go('F2')
    paste('11:00\t25:00')
    expect(page.locator('#sh-message')).to_contain_text('Nothing pasted')
    time('F2', '10:00:00')
    go('G2')
    paste('11:00\t12:00')
    expect(page.locator('#sh-message')).to_contain_text('read only')
    time('G2', '10:07:00')
    paste('=NOW()')
    expect(page.locator('#sh-message')).to_contain_text('Formulas are not supported')
    time('G2', '10:07:00')
    go('G7')
    paste('11:00\n12:00')
    expect(page.locator('#sh-message')).to_contain_text('past this page')

    # Fill right; a single cell uses the adjacent cell on its left.
    go('F2:G2')
    page.keyboard.press('Control+r')
    time('G2', '10:00:00')
    page.keyboard.press('Control+z')
    time('G2', '10:07:00')

    # Fill a selection from the text editor, including a midnight value.
    go('K2:K3')
    page.locator('[data-grid=edit]').click()
    page.get_by_role('textbox', name='Edit K3', exact=True).fill('12:00 AM')
    page.keyboard.press('Control+Enter')
    time('K2', '00:00:00')
    time('K3', '00:00:00')
    page.keyboard.press('Control+z')
    time('K2', '')
    time('K3', '')
    go('G2')
    page.keyboard.press('F2')
    page.get_by_role('textbox', name='Edit G2', exact=True).fill('25:99')
    page.keyboard.press('Enter')
    expect(page.locator('.sh-cell-editor')).to_have_attribute('aria-invalid', 'true')
    time('G2', '10:07:00')
    page.keyboard.press('Escape')
    page.keyboard.press('F2')
    page.keyboard.press('F8')
    expect(page.locator('#sh-grid-dialog-title')).to_have_text('Spreadsheet commands')
    page.keyboard.press('Escape')
    go('G2')
    page.keyboard.press('Control+r')
    time('G2', '10:00:00')
    page.keyboard.press('Control+z')

    # Flash fill keeps existing values, requires two examples, and previews first.
    go('G2:G6')
    page.keyboard.press('Control+e')
    expect(page.locator('#sh-grid-dialog-title')).to_have_text('Preview flash fill')
    expect(page.locator('.sh-flash-preview')).to_contain_text('10:11:00 AM')
    time('G4', '')
    page.screenshot(path=str(ROOT/'test-results/store-hours-flash-fill.png'))
    page.locator('#sh-flash-apply').click()
    time('G4', '10:11:00')
    time('G5', '10:13:00')
    time('G6', '10:15:00')
    page.keyboard.press('Control+z')
    time('G4', '')
    time('G6', '')
    page.keyboard.press('Control+y')
    time('G6', '10:15:00')

    # Cut is undoable; copied imported data cannot be edited or cut.
    go('G4:G6')
    page.keyboard.press('Control+x')
    time('G4', '')
    assert page.evaluate('navigator.clipboard.readText()').startswith('10:11:00')
    page.keyboard.press('Control+z')
    time('G4', '10:11:00')
    go('D1')
    page.keyboard.press('Delete')
    expect(cell('D1')).to_have_text('Opening Employee')
    page.keyboard.press('Control+x')
    expect(page.locator('#sh-message')).to_contain_text('only editable time cells')

    # Editing uses a plain time editor; Escape cancels without touching a draft.
    go('G2')
    page.keyboard.press('F2')
    page.get_by_role('textbox', name='Edit G2', exact=True).fill('11:59 PM')
    page.keyboard.press('Escape')
    time('G2', '10:07:00')
    page.keyboard.press('F2')
    page.get_by_role('textbox', name='Edit G2', exact=True).fill('11:59 PM')
    page.keyboard.press('Enter')
    time('G2', '23:59:00')
    expect(cell('G3')).to_be_focused()
    page.keyboard.press('Control+z')
    time('G2', '10:07:00')

    # F8 command keys replace Alt. Browser shortcuts outside the grid stay native.
    go('G2:G3')
    page.keyboard.press('F8')
    expect(page.locator('#sh-grid-dialog-title')).to_have_text('Spreadsheet commands')
    page.screenshot(path=str(ROOT/'test-results/store-hours-commands.png'))
    page.keyboard.press('d')
    time('G3', '10:07:00')
    page.keyboard.press('Control+z')
    time('G3', '10:09:00')
    go('G2')
    page.keyboard.press('Control+g')
    expect(page.locator('#sh-grid-address')).to_be_focused()
    go('G2')
    page.keyboard.press('Control+f')
    expect(page.locator('#sh-search')).to_be_focused()
    assert page.locator('#sh-search').evaluate("el=>{const e=new KeyboardEvent('keydown',{key:'r',ctrlKey:true,bubbles:true,cancelable:true});el.dispatchEvent(e);return !e.defaultPrevented}")

    go('A1')
    page.keyboard.press('Control+End')
    expect(cell('N7')).to_be_focused()
    page.keyboard.press('Control+Home')
    expect(cell('A1')).to_be_focused()
    page.keyboard.press('Shift+Space')
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(14)
    go('G1')
    page.keyboard.press('Control+Space')
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(7)
    page.keyboard.press('Control+a')
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(98)
    go('F2')
    page.keyboard.press('Tab')
    expect(cell('G2')).to_be_focused()
    page.keyboard.press('Shift+Tab')
    expect(cell('F2')).to_be_focused()
    cell('F2').click()
    cell('G3').click(modifiers=['Shift'])
    expect(page.locator('#sh-grid-address')).to_have_value('F2:G3')
    page.locator('#sh-table thead th').nth(6).click()
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(7)
    cell('A2').locator('.sh-row-number').click()
    expect(page.locator('#sh-table .sh-cell-selected')).to_have_count(14)
    go('F2')
    first=cell('F2').bounding_box()
    last=cell('G3').bounding_box()
    page.mouse.move(first['x']+first['width']/2, first['y']+first['height']/2)
    page.mouse.down()
    page.mouse.move(last['x']+last['width']/2, last['y']+last['height']/2, steps=8)
    page.mouse.up()
    expect(page.locator('#sh-grid-address')).to_have_value('F2:G3')
    go('N7')
    page.keyboard.press('Tab')
    expect(page.locator('[data-grid=commands]')).to_be_focused()
    go('G2')

    # Save persists independent rows; undo cannot replay stale revisions after save.
    page.keyboard.press('Control+s')
    expect(page.locator('#sh-message')).to_contain_text('Camera review saved')
    expect(page.locator('[data-grid=undo]')).to_be_disabled()
    expect(page.locator('#sh-unsaved')).to_be_empty()
    expect(cell('A1')).to_be_focused()
    page.locator('#sh-switch').click()
    expect(page.locator('#page-storehoursreport')).to_be_visible()
    go('G2')
    page.keyboard.press('F2')
    expect(page.locator('#sh-message')).to_contain_text('read only')
    assert page.locator('.sh-cell-editor').count() == 0
    paste('14:00')
    expect(page.locator('#sh-message')).to_contain_text('read only')
    expect(cell('G2')).to_have_text('10:07:00 AM')
    page.keyboard.press('Control+c')
    assert page.evaluate('navigator.clipboard.readText()') == '10:07:00'
    page.locator('#sh-switch').click()
    expect(page.locator('#page-storehours')).to_be_visible()
    go('G2:G4')
    page.screenshot(path=str(ROOT/'test-results/store-hours-spreadsheet.png'), full_page=True)
    page.reload()
    expect(page.locator('#sh-total')).to_have_text('7')
    expect(page.locator('.sh-sheet-welcome')).to_be_hidden()
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(ROOT/'test-results/store-hours-spreadsheet-mobile.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.locator('.sh-sheet-tools [data-grid=tutorial]').click()
    expect(page.locator('#sh-grid-dialog')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    print('Spreadsheet browser checks passed: navigation, ranges, clipboard, atomic validation, fills, flash preview, undo/redo, read-only rules, F8 commands, tutorial, save, and mobile.')


if __name__ == '__main__':
    main(check)
